/**
 * Writes src/usage/confusables.ts, the characters Unicode lists as
 * confusable, by which the usage panel tells apart account labels that read
 * alike, from Unicode's confusables.txt (UTS #39).
 *
 *   curl -O https://www.unicode.org/Public/security/latest/confusables.txt
 *   node scripts/confusables.mjs confusables.txt
 *
 * For a Unicode release, not for CI: the file is not kept here. The table
 * says the version and the file's SHA-256, and THIRD-PARTY-NOTICES.md gives
 * Unicode's licence, from scripts/unicode-license.txt.
 *
 * Each entry is a source character, its prototype, and their gap from the
 * entry before, in code points base 36; a run whose sources and prototypes
 * both step by one is one entry. Prototypes are kept decomposed, as the
 * skeleton's last step makes them, and it refuses a file in which one is not
 * its own skeleton, as UTS #39 makes them.
 */

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const [source] = process.argv.slice(2);
if (!source) {
    console.error('Usage: node scripts/confusables.mjs <confusables.txt>');
    process.exit(1);
}

const bytes = readFileSync(source);
const text = bytes.toString('utf8');
const version = /^# Version: (\d+\.\d+\.\d+)$/m.exec(text)?.[1];
const date = /^# Date: (\d{4}-\d{2}-\d{2})/m.exec(text)?.[1];
if (!version || !date) {
    console.error(`${source} says no version or date: not confusables.txt?`);
    process.exit(1);
}

const hexes = field => field.trim().split(/\s+/).map(hex => Number.parseInt(hex, 16));
const entries = [];
for (const line of text.split('\n')) {
    if (!/^[0-9A-F]/.test(line)) {
        continue;
    }
    const [from, to, type] = line.split('#')[0].split(';');
    const sources = hexes(from);
    if (sources.length !== 1 || type.trim() !== 'MA') {
        console.error(`An entry this table cannot hold: ${line}`);
        process.exit(1);
    }
    // Decomposed, as the skeleton's last step makes them: five are not, their marks out of order.
    entries.push([sources[0], [...String.fromCodePoint(...hexes(to)).normalize('NFD')].map(c => c.codePointAt(0))]);
}
entries.sort((a, b) => a[0] - b[0]);

const prototypes = new Map(entries.map(([s, p]) => [String.fromCodePoint(s), String.fromCodePoint(...p)]));
const skeleton = value => [...value.normalize('NFD')].map(c => prototypes.get(c) ?? c).join('').normalize('NFD');
for (const [s, p] of entries) {
    const prototype = String.fromCodePoint(...p);
    if (skeleton(prototype) !== prototype) {
        console.error(`U+${s.toString(16).toUpperCase()}: its prototype is not its own skeleton.`);
        process.exit(1);
    }
}

const encoded = [];
let previous = 0;
for (let i = 0; i < entries.length; ) {
    const [s, p] = entries[i];
    let run = 1;
    while (
        p.length === 1 &&
        i + run < entries.length &&
        entries[i + run][0] === s + run &&
        entries[i + run][1].length === 1 &&
        entries[i + run][1][0] === p[0] + run
    ) {
        run++;
    }
    encoded.push(`${(s - previous).toString(36)}${run > 1 ? `*${run.toString(36)}` : ''}:${p.map(c => c.toString(36)).join('.')}`);
    previous = s + run - 1;
    i += run;
}

const table = encoded.join(',');
const lines = [];
for (let at = 0; at < table.length; at += 100) {
    lines.push(`    '${table.slice(at, at + 100)}',`);
}
const sha256 = createHash('sha256').update(bytes).digest('hex');
const copyright = /^Copyright © .+$/m.exec(readFileSync(new URL('unicode-license.txt', import.meta.url), 'utf8'))?.[0];
if (!copyright) {
    console.error('scripts/unicode-license.txt says no copyright: not the Unicode License v3?');
    process.exit(1);
}

writeFileSync(
    new URL('../src/usage/confusables.ts', import.meta.url),
    [
        `// Generated by scripts/confusables.mjs from Unicode's confusables.txt (UTS #39),`,
        `// version ${version} of ${date}, SHA-256 ${sha256}.`,
        `// Do not edit. ${copyright}, under the Unicode License v3,`,
        '// which THIRD-PARTY-NOTICES.md reproduces.',
        '',
        '/** The version of Unicode the table is from. */',
        `export const CONFUSABLES_VERSION = '${version}';`,
        '',
        '/**',
        ` * The ${entries.length} characters Unicode lists as confusable, each with the`,
        ' * prototype it reads as, joined. In code points base 36: the gap from the',
        " * entry before, `*n` for a run of n whose sources and prototypes both step",
        " * by one, `:`, then the prototype's code points with `.` between them; `,`",
        ' * between entries.',
        ' */',
        'export const CONFUSABLES: readonly string[] = [',
        ...lines,
        '];',
        '',
    ].join('\n'),
);
console.log(`Wrote ${entries.length} confusables of Unicode ${version} (${date}) in ${encoded.length} entries, ${table.length} characters.`);
